DROP PROCEDURE IF EXISTS sp_calculate_sql_risk_score$$
CREATE PROCEDURE sp_calculate_sql_risk_score(IN p_transaction_id BIGINT, OUT p_risk_score DECIMAL(5,2))
BEGIN
    DECLARE v_amount DECIMAL(15,2);
    DECLARE v_account_id BIGINT;
    DECLARE v_avg_amount DECIMAL(15,2);
    DECLARE v_score DECIMAL(5,2) DEFAULT 0.00;
    
    SELECT amount, account_id INTO v_amount, v_account_id 
    FROM transactions WHERE transaction_id = p_transaction_id;
    
    SELECT AVG(amount) INTO v_avg_amount 
    FROM transactions WHERE account_id = v_account_id;
    
    IF v_amount > (v_avg_amount * 5) THEN
        SET v_score = v_score + 30.00;
    END IF;
    
    IF v_amount > 100000 THEN
        SET v_score = v_score + 20.00;
    END IF;
    
    SET p_risk_score = LEAST(v_score, 100.00);
END$$

DROP PROCEDURE IF EXISTS sp_generate_fraud_alert$$
CREATE PROCEDURE sp_generate_fraud_alert(
    IN p_transaction_id BIGINT, 
    IN p_risk_score DECIMAL(5,2), 
    IN p_risk_level VARCHAR(20)
)
BEGIN
    DECLARE v_customer_id BIGINT;
    DECLARE v_alert_id BIGINT;
    DECLARE v_alert_ref VARCHAR(20);
    
    SELECT a.customer_id INTO v_customer_id 
    FROM transactions t 
    JOIN accounts a ON t.account_id = a.account_id 
    WHERE t.transaction_id = p_transaction_id;
    
    SET v_alert_ref = CONCAT('AL', UNIX_TIMESTAMP());
    
    INSERT INTO fraud_alerts (transaction_id, customer_id, alert_ref, risk_level, status, detection_source)
    VALUES (p_transaction_id, v_customer_id, v_alert_ref, p_risk_level, 'NEW', 'SQL_ENGINE');
    
    SET v_alert_id = LAST_INSERT_ID();
    
    INSERT INTO risk_scores (alert_id, sql_risk_score, final_risk_score, scoring_details)
    VALUES (v_alert_id, p_risk_score, p_risk_score, 'Generated by sp_generate_fraud_alert');
    
    INSERT INTO notifications (customer_id, title, message, type)
    VALUES (v_customer_id, 'Fraud Alert Generated', CONCAT('Alert ', v_alert_ref, ' generated for transaction.'), 'FRAUD_ALERT');
END$$

DROP PROCEDURE IF EXISTS sp_get_customer_transaction_stats$$
CREATE PROCEDURE sp_get_customer_transaction_stats(IN p_customer_id BIGINT)
BEGIN
    WITH CTE_Tx AS (
        SELECT 
            t.transaction_id, 
            t.amount, 
            t.created_at,
            LAG(t.amount) OVER (ORDER BY t.created_at) as prev_amount,
            LEAD(t.amount) OVER (ORDER BY t.created_at) as next_amount,
            ROW_NUMBER() OVER (ORDER BY t.created_at DESC) as tx_order,
            RANK() OVER (ORDER BY t.amount DESC) as amt_rank
        FROM transactions t
        JOIN accounts a ON t.account_id = a.account_id
        WHERE a.customer_id = p_customer_id
    )
    SELECT * FROM CTE_Tx
    ORDER BY created_at DESC;
END$$

DROP PROCEDURE IF EXISTS sp_detect_rapid_transactions$$
CREATE PROCEDURE sp_detect_rapid_transactions(IN p_minutes INT, IN p_threshold INT)
BEGIN
    WITH CTE_Rapid AS (
        SELECT 
            a.customer_id,
            t.account_id,
            t.transaction_id,
            t.created_at,
            LAG(t.created_at, p_threshold - 1) OVER (PARTITION BY t.account_id ORDER BY t.created_at) as prev_time
        FROM transactions t
        JOIN accounts a ON t.account_id = a.account_id
    )
    SELECT customer_id, account_id, COUNT(*) as rapid_instances
    FROM CTE_Rapid
    WHERE prev_time IS NOT NULL 
    AND TIMESTAMPDIFF(MINUTE, prev_time, created_at) <= p_minutes
    GROUP BY customer_id, account_id
    HAVING COUNT(*) > 0;
END$$

